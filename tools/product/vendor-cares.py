#!/usr/bin/env python3
"""Export the immutable c-ares wire-only closure from the fixed-tag archive."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import tarfile

ROOT = Path(__file__).resolve().parents[2]
SHA256 = "ddf8be8b179ef6ff656e7413da93cf0f3038c627aca29ce9aae30f66e5b32bc1"
COMMIT = "c7a3138dcfe3bb0eaaf10c0c24c36dc66dc790ab"
SOURCES = [
    "record/ares_dns_parse.c", "record/ares_dns_write.c",
    "record/ares_dns_record.c", "record/ares_dns_name.c",
    "record/ares_dns_mapping.c", "record/ares_dns_multistring.c",
    "dsa/ares_array.c", "dsa/ares_llist.c",
    "str/ares_buf.c", "str/ares_str.c", "util/ares_math.c",
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path, nargs="?")
    parser.add_argument("--verify", action="store_true")
    args = parser.parse_args()
    destination = ROOT / "third_party/cares"
    if args.verify:
        manifest = json.loads((destination / "upstream-manifest.json").read_text())
        if (manifest["commit"] != COMMIT or manifest["archive_sha256"] != SHA256
                or manifest["sources"] != SOURCES):
            raise SystemExit("c-ares pin/closure identity mismatch")
        for relative, expected in manifest["files"].items():
            if hashlib.sha256((destination / "upstream" / relative).read_bytes()).hexdigest() != expected:
                raise SystemExit(f"c-ares source identity mismatch: {relative}")
        files = manifest["files"]
    elif args.archive is None:
        parser.error("archive or --verify is required")
    else:
        files = export(args.archive, destination)
    derive(destination, files, args.verify)


def export(archive_path, destination):
    if hashlib.sha256(archive_path.read_bytes()).hexdigest() != SHA256:
        raise SystemExit("c-ares archive identity mismatch")
    files = {}
    with tarfile.open(archive_path) as archive:
        for member in archive:
            if not member.isfile():
                continue
            relative = Path(*Path(member.name).parts[1:]).as_posix()
            if not (relative == "LICENSE.md" or relative.startswith("LICENSES/")
                    or relative.startswith("include/") and relative.endswith((".h", ".dist"))
                    or relative.startswith("src/lib/") and
                    (relative.endswith(".h") or relative[8:] in SOURCES
                     or relative == "src/lib/ares_getnameinfo.c")):
                continue
            data = archive.extractfile(member).read()
            target = destination / "upstream" / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            files[relative] = hashlib.sha256(data).hexdigest()
    manifest = {"source": "https://github.com/c-ares/c-ares", "tag": "v1.34.8",
                "commit": COMMIT, "archive_sha256": SHA256,
                "sources": SOURCES, "files": dict(sorted(files.items()))}
    (destination / "upstream-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return files


def derive(destination, files, verify):
    def output(path, expected):
        if verify:
            if path.read_text() != expected:
                raise SystemExit(f"c-ares generated export differs: {path.name}")
        else:
            path.write_text(expected)
    # The record convenience encoder depends on this pure helper, whose source
    # file otherwise pulls in the resolver channel. Retain that source verbatim
    # and export only the helper plus its original license, without a rewrite.
    onion_source = (destination / "upstream/src/lib/ares_getnameinfo.c").read_text()
    onion_helper = (onion_source[:onion_source.index('#include')]
                    + '#include "ares_private.h"\n\n'
                    + onion_source[onion_source.index("/* Determines if s1 ends"):])
    output(destination / "onion-helper.c", onion_helper)
    functions, macros = set(), set()
    for relative in files:
        text = (destination / "upstream" / relative).read_text()
        functions.update(re.findall(r"\b(ares_[A-Za-z0-9_]+)\s*\(", text))
        macros.update(re.findall(r"^\s*#\s*define\s+(ares_[A-Za-z0-9_]+)\b", text, re.M))
    functions -= macros
    output(destination / "namespace.h",
        "/* Generated by tools/product/vendor-cares.py; private codec symbols. */\n"
        "#ifndef SAKAMOTO_CARES_NAMESPACE_H\n#define SAKAMOTO_CARES_NAMESPACE_H\n"
        + "".join(f"#define {name} sakamoto_dns_{name}\n" for name in sorted(functions))
        + "#endif\n")
    output(destination / "sources.cmake", "# Generated by tools/product/vendor-cares.py.\n"
           + "set(cares_sources product_memory.c product_wire.c onion-helper.c\n"
           + "".join(f"  upstream/src/lib/{source}\n" for source in SOURCES
                     if source != "record/ares_dns_parse.c") + ")\n")
    print(f"c-ares wire closure: {len(files)} immutable files, {len(SOURCES)} compilation units")


if __name__ == "__main__":
    main()
