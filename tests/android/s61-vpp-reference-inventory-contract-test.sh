  intake_output="$("$provider_source_intake_gate" --evidence-root "$intake_dir")"
  grep -q '^providerSourceIntake=PASS$' <<<"$intake_output"
  grep -q '^providerSourceEvidence=predecision_intake_only$' <<<"$intake_output"
