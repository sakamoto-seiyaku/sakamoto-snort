#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)"
service="$repo_root/app/android-runtime/src/main/java/com/sakamoto/snort/androidruntime/RuntimeService.java"
native_status="$repo_root/app/android-runtime/src/main/java/com/sakamoto/snort/androidruntime/RuntimeControlNative.java"
jni="$repo_root/app/android-runtime/src/main/native/sakamoto_product_core_jni.c"
abi="$repo_root/src/product/include/sakamoto_product_abi.h"
api="$repo_root/src/product/vpp/product_core.api"
plugin="$repo_root/src/product/vpp/product_core_plugin.c"
graph_header="$repo_root/src/product/vpp/product_packet_graph.h"
graph="$repo_root/src/product/vpp/product_packet_graph.c"
root_adapter="$repo_root/src/product/vpp/product_root_nfqueue_adapter.c"
root_adapter_header="$repo_root/src/product/vpp/product_root_nfqueue_adapter.h"
device_runner="$repo_root/tests/device/s177-root-nfqueue-multilane-product.sh"

test -f "$service"
test -f "$native_status"
test -f "$jni"
test -f "$abi"
test -f "$api"
test -f "$plugin"
test -f "$graph_header"
test -f "$graph"
test -f "$root_adapter"
test -f "$root_adapter_header"
test -x "$device_runner"

grep -Fq 'PRODUCT_ROOT_NFQUEUE_QUEUE = "176"' "$service"
grep -Fq 'PRODUCT_ROOT_NFQUEUE_QUEUE_LAST = "177"' "$service"
grep -Fq 'PRODUCT_ROOT_NFQUEUE_LANES = "2"' "$service"
grep -Fq 'SAKAMOTO_PRODUCT_ROOT_NFQUEUE_LANES' "$service"
grep -Fq -- '--queue-balance " + queue + ":" + queueLast' "$service"
grep -Fq 'S177_ROOT_NFQUEUE_MULTILANE_STATUS' "$service"
grep -Fq 'queue_range=' "$service"
grep -Fq 'lane_count=' "$service"
grep -Fq 'ready_lane_mask=' "$service"
grep -Fq 'origin_local_completions=' "$service"
grep -Fq 'origin_remote_completions=' "$service"
grep -Fq 'lane0_verdict_attempts=' "$service"
grep -Fq 'lane1_verdict_attempts=' "$service"

grep -Fq 'root_nfqueue_queue_last' "$api"
grep -Fq 'root_nfqueue_lane_count' "$api"
grep -Fq 'root_nfqueue_ready_lane_mask' "$api"
grep -Fq 'root_nfqueue_origin_local_completions' "$api"
grep -Fq 'root_nfqueue_origin_remote_completions' "$api"
grep -Fq 'root_nfqueue_lane0_verdict_attempts' "$api"
grep -Fq 'root_nfqueue_lane1_verdict_attempts' "$api"
grep -Fq 'product_root_nfqueue_adapter_queue_last' "$plugin"
grep -Fq 'product_root_nfqueue_adapter_lane_count' "$plugin"
grep -Fq 'product_root_nfqueue_adapter_ready_lane_mask' "$plugin"
grep -Fq 'product_root_nfqueue_adapter_origin_local_completions' "$plugin"
grep -Fq 'product_root_nfqueue_adapter_origin_remote_completions' "$plugin"
grep -Fq 'product_root_nfqueue_adapter_lane_verdict_attempts (0)' "$plugin"
grep -Fq 'product_root_nfqueue_adapter_lane_verdict_attempts (1)' "$plugin"

grep -Fq 'root_nfqueue_queue_last' "$abi"
grep -Fq 'root_nfqueue_lane_count' "$abi"
grep -Fq 'root_nfqueue_ready_lane_mask' "$abi"
grep -Fq 'sizeof(sakamoto_product_status_t) == 1304U' "$abi"
grep -Fq 'STATUS_VALUE_COUNT = 135' "$jni"
grep -Fq 'STATUS_VALUE_COUNT = 135' "$native_status"
grep -Fq 'rootNfqueueQueueLast' "$native_status"
grep -Fq 'rootNfqueueLaneCount' "$native_status"
grep -Fq 'rootNfqueueReadyLaneMask' "$native_status"
grep -Fq 'rootNfqueueOriginLocalCompletions' "$native_status"
grep -Fq 'rootNfqueueOriginRemoteCompletions' "$native_status"
grep -Fq 'rootNfqueueLane0VerdictAttempts' "$native_status"
grep -Fq 'rootNfqueueLane1VerdictAttempts' "$native_status"

grep -Fq 'PRODUCT_ROOT_NFQUEUE_DEFAULT_LANES 2' "$root_adapter"
grep -Fq 'PRODUCT_ROOT_NFQUEUE_MAX_LANES' "$root_adapter"
grep -Fq 'product_root_nfqueue_lane_t lanes[PRODUCT_ROOT_NFQUEUE_MAX_LANES]' "$root_adapter"
grep -Fq 'SAKAMOTO_PRODUCT_ROOT_NFQUEUE_LANES' "$root_adapter"
grep -Fq 'product_root_nfqueue_obligation_id' "$root_adapter"
grep -Fq 'product_root_nfqueue_decode_obligation' "$root_adapter"
grep -Fq 'template.private_data = pointer_to_uword (lane)' "$root_adapter"
grep -Fq 'uword_to_pointer (file->private_data, product_root_nfqueue_lane_t *)' "$root_adapter"
grep -Fq 'hints.interface_id = lane->lane_index' "$root_adapter"
grep -Fq 'product_packet_graph_external_result_t graph_result' "$root_adapter"
grep -Fq 'lane->fd, lane->queue_id, packet_id' "$root_adapter"
grep -Fq 'lane->origin_local_completions++' "$root_adapter"
grep -Fq 'lane->origin_remote_completions++' "$root_adapter"
grep -Fq 'nm->ready_lane_mask |= 1U << lane->lane_index' "$root_adapter"
if grep -Eq 'nfq_set_verdict_batch|pthread_mutex|trylock|shared[_-]?tx|nm->fd|nm->clib_file_index' "$root_adapter"; then
  echo "S177 Root adapter contains rejected shared/batch/singleton verdict ownership" >&2
  exit 1
fi

grep -Fq 'product_packet_graph_external_result_t' "$graph_header"
grep -Fq 'external_result->arrival_worker' "$graph"
grep -Fq 'external_result->owner_worker' "$graph"
grep -Fq 'external_result->primary_remote' "$graph"
grep -Fq '.worker_count = PRODUCT_GRAPH_WORKERS' "$graph"
grep -Fq 'hints->interface_id % PRODUCT_GRAPH_WORKERS' "$graph"
grep -Fq 'product_handoff_credit_reserve' "$graph"
grep -Fq 'product_packet_owner_guard (&lease, lease.expected_owner)' "$graph"
grep -Fq 'PRODUCT_PACKET_DROP_PRIMARY_HANDOFF_CONGESTION' "$graph"

grep -Fq 'S177_ADDRESS_DIVERSE_HOST' "$device_runner"
grep -Fq 'address_diverse_host="${S177_ADDRESS_DIVERSE_HOST:-}"' "$device_runner"
grep -Fq 'ip route replace ${address_diverse_host}/32' "$device_runner"
grep -Fq 'cleanup_address_diverse_route' "$device_runner"
grep -Fq 'if [[ -n "$address_diverse_host" ]]' "$device_runner"
grep -Fq 'address_diverse_strategy "source-port-rotation"' "$device_runner"
grep -Fq 'kv address_diverse_host' "$device_runner"
grep -Fq 'lane1_verdict_attempts>=1' "$device_runner"
if grep -Fq 'source_port=$((20000 + attempt))' "$device_runner"; then
  echo "S177 runner still relies on port-only variation for queue-balance coverage" >&2
  exit 1
fi

echo "sakamoto-177 Root NFQUEUE multi-lane contract: PASS"
